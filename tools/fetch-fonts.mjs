// Downloads the typefaces in tools/fonts.json into public/fonts, verifies each
// one, and writes src/font-library.js (the app's FONT_LIBRARY).
//
//   node tools/fetch-fonts.mjs          download missing fonts, verify all
//   node tools/fetch-fonts.mjs --check  verify only (no network); used in CI
//
// A font is accepted only if its licence passes the app's own OFL reader without
// an ambiguous reserved-name clause, opentype.js parses it, it covers A-Z a-z 0-9,
// and its bytes match the SHA-256 pinned in tools/fonts.lock.json.
import fs from 'node:fs';
import path from 'node:path';
import crypto from 'node:crypto';
import opentype from 'opentype.js';
import {readLicense} from '../src/model.js';

const root = path.resolve(path.dirname(new URL(import.meta.url).pathname), '..');
const manifest = JSON.parse(fs.readFileSync(path.join(root, 'tools/fonts.json'), 'utf8'));
const lockPath = path.join(root, 'tools/fonts.lock.json');
const lock = fs.existsSync(lockPath) ? JSON.parse(fs.readFileSync(lockPath, 'utf8')) : {};
const checkOnly = process.argv.includes('--check');
const fontsDir = path.join(root, 'public/fonts');
const sha = (buf) => crypto.createHash('sha256').update(buf).digest('hex');
const REQUIRED = 'ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz0123456789';

async function fetchBytes(url) {
  const res = await fetch(url);
  if (!res.ok) throw Error(`${url}: HTTP ${res.status}`);
  return Buffer.from(await res.arrayBuffer());
}

const library = [];
let failures = 0;
for (const f of manifest.fonts) {
  const fontRel = f.builtin ? f.builtin.url : `/fonts/${f.id}.woff`;
  const licRel = f.builtin ? f.builtin.license : `/fonts/OFL-${f.id}.txt`;
  const fontFile = path.join(root, 'public', fontRel), licFile = path.join(root, 'public', licRel);
  try {
    if (!f.builtin && !(fs.existsSync(fontFile) && fs.existsSync(licFile))) {
      if (checkOnly) throw Error('missing; run without --check');
      const base = `https://cdn.jsdelivr.net/npm/@fontsource/${f.pkg}@${f.version}`;
      fs.writeFileSync(fontFile, await fetchBytes(`${base}/files/${f.pkg}-latin-${f.weight}-normal.woff`));
      fs.writeFileSync(licFile, await fetchBytes(`${base}/LICENSE`));
    }
    const bytes = fs.readFileSync(fontFile), text = fs.readFileSync(licFile, 'utf8');
    const lic = readLicense(text);
    if (!lic.ofl) throw Error('licence is not a complete SIL OFL 1.1');
    if (lic.ambiguous) throw Error('licence has an ambiguous Reserved Font Name clause');
    const font = opentype.parse(bytes.buffer.slice(bytes.byteOffset, bytes.byteOffset + bytes.byteLength));
    const missing = [...REQUIRED].filter((c) => font.charToGlyph(c).index === 0);
    if (missing.length) throw Error(`missing glyphs: ${missing.join('')}`);
    const digest = { font: sha(bytes), license: sha(Buffer.from(text)) };
    if (lock[f.id] && (lock[f.id].font !== digest.font || lock[f.id].license !== digest.license)) throw Error('checksum differs from tools/fonts.lock.json');
    if (!lock[f.id]) { if (checkOnly) throw Error('not in tools/fonts.lock.json'); lock[f.id] = digest; }
    library.push({ id: f.id, name: f.name, style: f.style, group: f.group, url: fontRel, license: licRel, reserved: lic.reserved });
    console.log(`ok   ${f.id.padEnd(16)} ${f.name}${lic.reserved.length ? `  (reserved: ${lic.reserved.join(', ')})` : ''}`);
  } catch (e) {
    failures++;
    console.log(`FAIL ${f.id.padEnd(16)} ${e.message}`);
  }
}
if (failures) { console.error(`${failures} font(s) failed`); process.exit(1); }
if (!checkOnly) fs.writeFileSync(lockPath, JSON.stringify(lock, null, 2) + '\n');
const out = `// Generated by tools/fetch-fonts.mjs from tools/fonts.json. Do not edit by hand.\nexport const FONT_GROUPS = ${JSON.stringify(manifest.groups)};\nexport const FONT_LIBRARY = ${JSON.stringify(library.map(({ reserved, ...rest }) => rest), null, 1)};\n`;
const target = path.join(root, 'src/font-library.js');
if (checkOnly) {
  if (fs.readFileSync(target, 'utf8') !== out) { console.error('src/font-library.js is out of date; run node tools/fetch-fonts.mjs'); process.exit(1); }
} else fs.writeFileSync(target, out);
console.log(`${library.length} fonts verified`);
